# ── photo supply ────────────────────────────────────────────────────────────

def _cached_faces() -> list[Path]:
    if not _CACHE_DIR.exists():
        return []
    return sorted(p for p in _CACHE_DIR.iterdir()
                  if p.suffix.lower() in {".jpg", ".jpeg", ".png"})


def _fetch_face() -> Path | None:
    """Pull one generated portrait into the cache. Returns its path, or None.

    Named by content hash so an unlucky duplicate from the generator does not
    occupy two cache slots and two enrolment attempts.
    """
    import httpx

    try:
        response = httpx.get(_FACE_URL, headers={"Referer": _REFERER},
                             timeout=30.0, follow_redirects=True)
    except Exception as exc:
        log.warning("could not reach the face generator: %s", exc)
        return None
    ctype = response.headers.get("content-type", "")
    if response.status_code != 200 or not ctype.startswith("image/"):
        log.warning("face generator answered HTTP %s (%s)",
                    response.status_code, ctype or "no content type")
        return None

    _CACHE_DIR.mkdir(parents=True, exist_ok=True)
    digest = hashlib.sha256(response.content).hexdigest()[:16]
    path = _CACHE_DIR / f"{digest}.jpg"
    if not path.exists():
        path.write_bytes(response.content)
    return path


class FaceSupply:
    """Hands out one usable, not-yet-used portrait at a time.

    Encoding can legitimately fail on a generated image (an unusual crop, a
    profile view), so a caller that simply took the next file would leave a
    record unenrolled for no reason. This retries with a fresh face instead,
    and falls back to the cache when the network is unavailable.
    """

    def __init__(self, *, offline: bool = False) -> None:
        self._offline = offline
        self._pool = _cached_faces()
        self._used: set[Path] = set()
        self._last_fetch = 0.0

    def _next_path(self) -> Path | None:
        for path in self._pool:
            if path not in self._used:
                return path
        if self._offline:
            return None
        gap = _FETCH_GAP - (time.monotonic() - self._last_fetch)
        if gap > 0:
            time.sleep(gap)
        self._last_fetch = time.monotonic()
        path = _fetch_face()
        if path is None:
            return None
        if path not in self._pool:
            self._pool.append(path)
        return None if path in self._used else path

    def take(self, *, attempts: int = 4) -> tuple[object, dict] | None:
        """Returns (PIL image, encode_reference result) or None."""
        from PIL import Image

        for _ in range(attempts):
            path = self._next_path()
            if path is None:
                continue
            self._used.add(path)
            try:
                img = Image.open(path)
                img.load()
            except Exception as exc:
                log.warning("unreadable cached face %s: %s", path.name, exc)
                continue
            ref = encode_reference(img)
            if ref.get("ok"):
                return img, ref
            log.info("skipping %s — %s", path.name, ref.get("error"))
        return None


# ── enrolment ───────────────────────────────────────────────────────────────

def _enrol(session, suspect: Suspect, supply: FaceSupply) -> bool:
    taken = supply.take()
    if taken is None:
        log.warning("no usable portrait available for %s", suspect.full_name)
        return False
    img, ref = taken
    thumb = face_db.crop_thumb(img, ref["bounding_box"])
    added = face_db.add_template(session, suspect, encoding=ref["encoding"],
                                 quality=ref["quality"],
                                 source="synthetic reference (StyleGAN)",
                                 thumb=thumb)
    if not added.get("ok"):
        log.warning("could not enrol %s: %s", suspect.full_name, added.get("error"))
        return False
    log.info("enrolled %-22s quality=%s", suspect.full_name, ref["quality"]["score"])
    return True


def seed(*, offline: bool = False) -> dict:
    supply = FaceSupply(offline=offline)
    augmented = created = enrolled = 0

    with session_scope() as s:
        # Pass 1 — complete the records suspect_seed.py left half-finished.
        for name, extra in _AUGMENT.items():
            row = s.exec(select(Suspect)
                         .where(col(Suspect.full_name) == name)).first()
            if row is None:
                continue
            changed = False
            for field, value in extra.items():
                if not getattr(row, field, None):
                    setattr(row, field, value)
                    changed = True
            if changed:
                if _SYNTHETIC_NOTE not in (row.notes or ""):
                    row.notes = ((row.notes or "") + " " + _SYNTHETIC_NOTE).strip()
                row.updated_at = utcnow()
                s.add(row)
                s.commit()
                augmented += 1
            if not (row.face_templates or []):
                if _enrol(s, row, supply):
                    enrolled += 1

        # Pass 2 — the new records.
        for template in _NEW:
            data = dict(template)
            extra_note = data.pop("notes_extra", "")
            name = data["full_name"]
            row = s.exec(select(Suspect)
                         .where(col(Suspect.full_name) == name)).first()
            if row is None:
                data["notes"] = (extra_note + " " if extra_note else "") + _DEMO_NOTE
                row = Suspect(**data, source=DEMO_SOURCE)
                s.add(row)
                s.commit()
                s.refresh(row)
                created += 1
            if not (row.face_templates or []):
                if _enrol(s, row, supply):
                    enrolled += 1

    return {"augmented": augmented, "created": created, "enrolled": enrolled}


def reset() -> dict:
    """Undo this script: delete its own records, un-enrol what it added.

    The four `source="seed"` rows are *not* deleted — they predate this script
    and suspect_seed.py owns them. Their synthetic templates are stripped,
    which returns them to the unenrolled state they ship in. Analyst-created
    records are never touched.
    """
    deleted = stripped = 0
    with session_scope() as s:
        for row in s.exec(select(Suspect)
                          .where(col(Suspect.source) == DEMO_SOURCE)).all():
            s.delete(row)
            deleted += 1
        s.commit()

        for name in _AUGMENT:
            row = s.exec(select(Suspect)
                         .where(col(Suspect.full_name) == name)).first()
            if row is None or not (row.face_templates or []):
                continue
            kept = [t for t in row.face_templates
                    if "StyleGAN" not in (t.get("source") or "")]
            if len(kept) != len(row.face_templates):
                row.face_templates = kept
                if not kept:
                    row.photo_thumb = ""
                row.updated_at = utcnow()
                s.add(row)
                stripped += 1
        s.commit()
    return {"deleted": deleted, "unenrolled": stripped}


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Seed the suspect registry with synthetic faces and full "
                    "classifications, so identification is demonstrable.")
    parser.add_argument("--reset", action="store_true",
                        help="remove the records this script created and "
                             "un-enrol the photos it added")
    parser.add_argument("--offline", action="store_true",
                        help="use only portraits already cached in "
                             ".demo_faces/; never reach the network")
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")

    if args.reset:
        result = reset()
        print(f"removed {result['deleted']} demo record(s), "
              f"un-enrolled {result['unenrolled']} seeded record(s)")
        return

    result = seed(offline=args.offline)
    print(f"augmented {result['augmented']} seeded record(s), "
          f"created {result['created']} new record(s), "
          f"enrolled {result['enrolled']} reference photo(s)")
    print(f"portrait cache: {_CACHE_DIR}")


if __name__ == "__main__":
    main()
