"""Demo registry with enrolled faces — synthetic people, real pipeline.

`suspect_seed.py` deliberately ships records with no face template, because a
template can only honestly come from a photo somebody enrolled. That is the
right default for a fresh install, and it also means the identification half of
the tool has nothing to demonstrate until an analyst uploads something. This
script is that analyst, run from the terminal.

Every face here is generated by StyleGAN (thispersondoesnotexist.com) and
depicts **nobody**. That is not a detail — this registry attaches criminal
records, charge sheets and risk levels to a face, and a confirmed match asserts
that record against whoever is standing in front of the camera. Pointing that
machinery at a photograph of a real person is how a demo turns into an
accusation, so the images are synthetic by construction and every row created
here says so in its notes.

What it does, in two passes:

  1. the four `source="seed"` records get the reference photo and the physical
     descriptors they were always missing (height, occupation, marks), which is
     what makes them matchable at all
  2. six new `source="demo_seed"` records are created across the record types,
     each fully classified — height, age, occupation, charges, convictions,
     case IDs, jurisdiction — so the registry exercises ranking, the filters
     and the ambiguous-match path rather than returning one row

Idempotent: a record that already carries a template is left alone, so re-runs
are free. Photos are cached under `backend/.demo_faces/` and only fetched once.

    python -m app.data.face_demo_seed              # seed / top up
    python -m app.data.face_demo_seed --reset      # remove what it created
    python -m app.data.face_demo_seed --offline    # cache only, no network

Writes through the ORM rather than the HTTP API on purpose: `POST /api/faces/
enroll` takes only a handful of Form fields and cannot set height, occupation,
age, gender or charges at all, so the API route could not produce these records.
"""
